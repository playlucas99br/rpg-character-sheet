const ritual = (
  name: string,
  element: KnownRitual["element"],
  circle: number,
  summary: string,
): KnownRitual => {
  const id = `ritual-${name.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]+/g, "-")}`;
  const details = ORDEM_RITUAL_DETAILS[id];
  if (!details) throw new Error(`Missing local ritual detail entry: ${name}`);
  return {
  id,
  name,
  element,
  circle,
  summary,
  ...details,
};
};

